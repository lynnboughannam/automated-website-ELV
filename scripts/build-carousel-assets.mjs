// Generates lib/carousel/assets.generated.ts: fonts + logos inlined as base64,
// so the render route needs no file system or network access for brand assets.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const font = (pkg, file) =>
  readFileSync(require.resolve(`@fontsource/${pkg}/files/${file}`)).toString("base64");
const png = (p) => readFileSync(p).toString("base64");
const out = process.argv[2] ?? "lib/carousel/assets.generated.ts";
const assetsDir = process.argv[3] ?? "lib/carousel/assets";
const data = {
  playfair700: font("playfair-display", "playfair-display-latin-700-normal.woff2"),
  playfair400i: font("playfair-display", "playfair-display-latin-400-italic.woff2"),
  nunito400: font("nunito-sans", "nunito-sans-latin-400-normal.woff2"),
  nunito600: font("nunito-sans", "nunito-sans-latin-600-normal.woff2"),
  nunito700: font("nunito-sans", "nunito-sans-latin-700-normal.woff2"),
  nunito800: font("nunito-sans", "nunito-sans-latin-800-normal.woff2"),
  logoWhite: png(`${assetsDir}/logo-white.png`),
  logoBrown: png(`${assetsDir}/logo-brown.png`),
  iconWhite: png(`${assetsDir}/icon-white.png`),
  iconBrown: png(`${assetsDir}/icon-brown.png`),
};
mkdirSync(out.split("/").slice(0, -1).join("/") || ".", { recursive: true });
writeFileSync(
  out,
  "// AUTO-GENERATED by scripts/build-carousel-assets.mjs. Do not edit.\n" +
    "export const ASSETS = " + JSON.stringify(data) + " as const;\n"
);
console.log("wrote", out);
